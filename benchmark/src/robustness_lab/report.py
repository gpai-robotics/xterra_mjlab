def _display(value: Any) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, float):
        return "%.5g" % value
    return str(value)


def generate_report(run_dir: str, output_path: str) -> str:
    root = Path(run_dir).resolve()
    manifest = load_data(str(root / "manifest.json"))
    episode = load_data(str(root / "resolved_episode.json"))
    robot = load_data(episode["robot_profile"])
    world = load_data(episode["world"])
    log = load_data(str(root / "episode_log.json"))
    metrics_path = root / "metrics.json"
    metric_payload = load_data(str(metrics_path)) if metrics_path.exists() else {"metrics": []}
    families: Dict[str, List[Dict[str, Any]]] = {}
    csv_rows = []
    for metric in metric_payload.get("metrics", []):
        value = dict(metric)
        value["display"] = _display(value.get("value"))
        ci = ""
        if value.get("lower_ci") is not None:
            ci = "95% CI %s–%s" % (_display(value["lower_ci"]), _display(value["upper_ci"]))
        value["note"] = ci or ("valid" if value.get("valid") else value.get("reason", "invalid"))
        families.setdefault(value.get("family", "other"), []).append(value)
        csv_rows.append({key: metric.get(key) for key in ("family", "name", "value", "unit", "valid", "reason", "lower_ci", "upper_ci")})
    metric_index = {item["name"]: item for items in families.values() for item in items}
    highlight_names = ["success", "completion_time", "goal_distance", "velocity_tracking_rmse", "slip_ratio", "absolute_mechanical_cot", "inference_latency_p95", "real_time_factor"]
    highlights = [metric_index[name] for name in highlight_names if name in metric_index]
    events = []
    for event in log.get("events", []):
        event = dict(event)
        event["details_json"] = json.dumps(event.get("details", {}), sort_keys=True)
        events.append(event)
    environment = Environment(loader=BaseLoader(), autoescape=select_autoescape(["html", "xml"]))
    rendered = environment.from_string(TEMPLATE).render(
        manifest=manifest,
        manifest_json=json.dumps(manifest, indent=2, sort_keys=True),
        episode=episode,
        robot=robot,
        world=world,
        log=log,
        families=dict(sorted(families.items())),
        highlights=highlights,
        events=events,
        comparability=json.dumps(manifest.get("comparability", {}), indent=2, sort_keys=True),
        diagnostics=json.dumps(log.get("diagnostics", {}), indent=2, sort_keys=True),
    )
    atomic_write_text(output_path, rendered)
    write_csv(str(Path(output_path).with_suffix(".metrics.csv")), csv_rows)
    return output_path


def generate_aggregate_report(aggregate_path: str, output_path: str) -> str:
    aggregate = load_data(aggregate_path)
    selected = {"success", "completion_time", "progress_fraction", "velocity_tracking_rmse", "slip_ratio", "absolute_mechanical_cot", "recovery_time_mean", "inference_latency_p95", "real_time_factor"}
    summary_rows = []
    for backend, metrics in sorted(aggregate.get("backend_summaries", {}).items()):
        for name, record in sorted(metrics.items()):
            if name in selected:
                summary_rows.append({"backend": backend, "name": name, **record})
    all_points = [point for curve in aggregate.get("capability_curves", {}).values() for point in curve.get("curve", [])]
    severities = [float(point["severity"]) for point in all_points]
    low, high = (min(severities), max(severities)) if severities else (0.0, 1.0)
    width = max(high - low, 1e-9)
    palette = ["#0072b2", "#d55e00", "#009e73", "#cc79a7", "#e69f00"]
    curve_series = []
    for index, (backend, curve) in enumerate(sorted(aggregate.get("capability_curves", {}).items())):
        points = " ".join("%.3f,%.3f" % (70.0 + 900.0 * (float(item["severity"]) - low) / width, 250.0 - 230.0 * float(item["success_rate"])) for item in curve.get("curve", []))
        curve_series.append({"backend": backend, "points": points, "color": palette[index % len(palette)]})
    environment = Environment(loader=BaseLoader(), autoescape=select_autoescape(["html", "xml"]))
    environment.filters["display"] = _display
    rendered = environment.from_string(AGGREGATE_TEMPLATE).render(
        aggregate=aggregate,
        aggregate_json=json.dumps(aggregate, indent=2, sort_keys=True),
        comparability=json.dumps(aggregate.get("comparability", {}), indent=2, sort_keys=True),
        summary_rows=summary_rows,
        curve_series=curve_series,
    )
    atomic_write_text(output_path, rendered)
    return output_path
